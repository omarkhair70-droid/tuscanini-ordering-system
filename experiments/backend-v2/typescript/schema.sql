-- Disposable, independent PostgreSQL 16 schema. NEVER run against merchant data.
CREATE SCHEMA IF NOT EXISTS spike_ts;

CREATE TABLE spike_ts.catalog_item (
  sku varchar(64) PRIMARY KEY,
  name varchar(160) NOT NULL,
  unit_price_cents integer NOT NULL CHECK (unit_price_cents >= 0),
  available boolean NOT NULL DEFAULT TRUE
);
CREATE TABLE spike_ts.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_key varchar(80) NOT NULL UNIQUE,
  payload_sha256 char(64) NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'received',
  subtotal_cents bigint NOT NULL CHECK (subtotal_cents >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE spike_ts.order_line (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES spike_ts.orders(id) ON DELETE RESTRICT,
  sku_snapshot varchar(64) NOT NULL,
  name_snapshot varchar(160) NOT NULL,
  unit_price_cents integer NOT NULL CHECK (unit_price_cents >= 0),
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 100),
  line_total_cents bigint NOT NULL CHECK (line_total_cents >= 0)
);
CREATE INDEX ts_order_line_order_idx ON spike_ts.order_line(order_id);

CREATE TABLE spike_ts.order_status_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES spike_ts.orders(id) ON DELETE RESTRICT,
  status varchar(24) NOT NULL,
  detail varchar(200) NOT NULL,
  actor_role varchar(20) NOT NULL DEFAULT 'system',
  action varchar(50) NOT NULL DEFAULT 'receive',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ts_order_events_order_idx ON spike_ts.order_status_event(order_id, created_at);
CREATE TABLE spike_ts.outbox_event (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL REFERENCES spike_ts.orders(id) ON DELETE RESTRICT,
  kind varchar(80) NOT NULL,
  payload jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  delivered_at timestamptz
);
CREATE INDEX ts_outbox_unsent_idx
  ON spike_ts.outbox_event(created_at, id)
  WHERE delivered_at IS NULL;

CREATE TABLE spike_ts.payment_attempt (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES spike_ts.orders(id) ON DELETE RESTRICT,
  provider_reference varchar(120),
  status varchar(24) NOT NULL DEFAULT 'initiated',
  amount_cents bigint NOT NULL CHECK (amount_cents >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);
